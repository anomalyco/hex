#!/usr/bin/env python3
"""Builds the Android keyboard's English emoji search index.

The iPhone keyboard's emoji index (ios/HEXShared/FullKeyboard/Emoji/emoji-index-en.txt)
is generated by ios/scripts/build-emoji-data.py from Unicode emoji-test.txt 18.0,
CLDR 49 annotations, and Hex's own chat words. Its emoji panel searches each emoji's
name and keywords (EmojiLibrary.search); the Android keyboard's emoji search
(Labs › Keyboard › Emoji search) does the same, so this keeps only that column of each
emoji line, in the iPhone catalog's order, and drops the word, phrase and stopword
tables the strip's suggestions use.

    python3 android/scripts/build-emoji-search.py

Writes android/app/src/main/assets/emoji/search-en.txt: one "emoji<TAB>name|keywords"
line per emoji. The words are already folded (lowercase, unaccented, apostrophes
straight) by the iOS index, so the keyboard folds only what is typed.
"""

import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCE = REPO / "ios" / "HEXShared" / "FullKeyboard" / "Emoji" / "emoji-index-en.txt"
OUT = HERE.parent / "app" / "src" / "main" / "assets" / "emoji" / "search-en.txt"

# What the search promises, checked so a source update cannot quietly drop one.
REQUIRED = {"😂": "laugh", "❤️": "heart", "👍": "thumbs", "🎉": "party"}

HEADER = (
    "# Generated by android/scripts/build-emoji-search.py; do not edit.\n"
    "# From the iOS keyboard's emoji-index-en.txt: Unicode emoji-test.txt 18.0 and\n"
    "# CLDR 49 annotations (Unicode License v3, assets/licenses/unicode.txt), and\n"
    "# Hex's own chat words (ios/scripts/emoji-aliases-en.txt).\n"
    "# emoji<TAB>name words|keywords, in the iPhone catalog's order\n"
)


def main():
    rows = []
    for raw in SOURCE.read_text(encoding="utf-8").splitlines():
        parts = raw.split("\t")
        if parts[0] == "E":
            rows.append((parts[1], parts[7]))
    found = dict(rows)
    for emoji, word in REQUIRED.items():
        if word not in found.get(emoji, "").replace("|", " ").split():
            raise SystemExit(f"{emoji}: {word!r} missing from {found.get(emoji)!r}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "".join(f"{e}\t{words}\n" for e, words in rows), encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(rows)} emoji, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
