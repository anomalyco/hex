#!/usr/bin/env python3
"""Builds the Android keyboard's emoji shortcode index (Labs › Keyboard › Emoji shortcodes).

The iPhone keyboard's emoji index (ios/HEXShared/FullKeyboard/Emoji/emoji-index-en.txt)
is generated by ios/scripts/build-emoji-data.py from Unicode emoji-test.txt 18.0,
CLDR 49 annotations, and Hex's own chat words. iPhone Hex's shortcodes (EmojiShortcode)
read three things from it: each emoji's version, family and search words (its name's
words, "|", its keywords), and the exact names and aliases of the word and phrase
tables. This keeps exactly those, in the same order, so entry numbers still match:

  - E lines keep emoji, version, family and search words (no category or skin tones);
  - W and P lines keep only postings at or above the iPhone's strong line (0.85,
    EmojiSuggester.strongWeight), which are names and aliases, never keywords, and
    drop a word or phrase with none.

    python3 android/scripts/build-emoji-shortcodes.py

Writes android/app/src/main/assets/emoji/shortcodes-en.txt.
"""

import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
SOURCE = REPO / "ios" / "HEXShared" / "FullKeyboard" / "Emoji" / "emoji-index-en.txt"
OUT = HERE.parent / "app" / "src" / "main" / "assets" / "emoji" / "shortcodes-en.txt"

STRONG = 0.85

# Shortcodes the feature promises, checked after filtering so a source update cannot
# quietly drop one: an exact word, an alias with "_" and a phrase.
REQUIRED = {"W\tfire": "🔥", "W\tpizza": "🍕", "P\tthumbs up": "👍"}

HEADER = (
    "# Generated by android/scripts/build-emoji-shortcodes.py; do not edit.\n"
    "# From the iOS keyboard's emoji-index-en.txt: Unicode emoji-test.txt 18.0 and\n"
    "# CLDR 49 annotations (Unicode License v3, assets/licenses/unicode.txt), and\n"
    "# Hex's own chat words (ios/scripts/emoji-aliases-en.txt).\n"
    "# E emoji, version, family, search words (name's | keywords'), numbered by line;\n"
    "# W word, P phrase: entry:weight for names and aliases (weight 0.85 and up).\n"
)


def main():
    emoji = []
    out = []
    first = {}
    for raw in SOURCE.read_text(encoding="utf-8").splitlines():
        parts = raw.split("\t")
        if parts[0] == "E":
            if len(parts) != 8:
                raise SystemExit(f"unexpected emoji line: {raw!r}")
            _, glyph, _category, version, _tones, family, _name, search = parts
            emoji.append(glyph)
            out.append(f"E\t{glyph}\t{version}\t{family}\t{search}\n")
        elif parts[0] in ("W", "P"):
            kind, key, postings = parts
            strong = [p for p in postings.split(",") if float(p.rsplit(":", 1)[1]) >= STRONG]
            if strong:
                out.append(f"{kind}\t{key}\t{','.join(strong)}\n")
                first[f"{kind}\t{key}"] = emoji[int(strong[0].split(":", 1)[0])]
    for key, expected in REQUIRED.items():
        if first.get(key) != expected:
            raise SystemExit(f"{key!r}: expected {expected}, got {first.get(key)}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "".join(out), encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(emoji)} emoji, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
