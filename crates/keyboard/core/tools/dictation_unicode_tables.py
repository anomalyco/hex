#!/usr/bin/env python3
"""Writes core/src/dictation/unicode_generated.rs from the parity exporter's per-scalar dump of
iOS's Unicode data (DictationParityTests, TEST_RUNNER_HEX_DICTATION_UNICODE_OUT):

    python3 crates/keyboard/core/tools/dictation_unicode_tables.py /tmp/dictation-unicode.tsv

The tables are what iOS reads where Rust's own data differs or has nothing: Character's
isLetter and isNumber, the ICU sets NSRegularExpression matches (\\p{L}, \\p{N}, the word
set \\b reads, Grapheme_Extend and Cf), CoreFoundation's Grapheme_Extend set and its
`folding` of each scalar. Case mappings and White_Space come from Rust's std, which the
Unicode test (HEX_DICTATION_UNICODE) checks against the same dump.
"""

import os
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "dictation", "unicode_generated.rs")

SETS = [
    ("LETTER", "L", "`Character.isLetter` of the scalar (Alphabetic, and Apple's private-use letters)."),
    ("NUMBER", "N", "`Character.isNumber` of the scalar (Numeric_Type, Han numerals included)."),
    ("ICU_LETTER", "p", "ICU's `\\p{L}`."),
    ("ICU_NUMBER", "d", "ICU's `\\p{N}`."),
    ("ICU_WORD", "w", "ICU's `\\b` word set, `[\\p{Alphabetic}\\p{M}\\p{Nd}\\p{Pc}\\u200c\\u200d]`."),
    ("ICU_EXTEND", "e", "What ICU's `\\b` never stops before: `[\\p{Grapheme_Extend}\\p{Cf}]`."),
]


def ranges(values):
    out = []
    for v in values:
        if out and out[-1][1] == v - 1:
            out[-1][1] = v
        else:
            out.append([v, v])
    return out


def table(name, doc, values):
    lines = ["/// " + doc, "#[rustfmt::skip]", "pub(super) static %s: &[(u32, u32)] = &[" % name]
    row = []
    for lo, hi in ranges(values):
        row.append("(0x%X, 0x%X)," % (lo, hi))
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def main():
    members = {flag: [] for _, flag, _ in SETS}
    cf_extend = []
    folds = []
    for line in open(sys.argv[1], encoding="utf-8"):
        fields = line.rstrip("\n").split("\t")
        value = int(fields[0], 16)
        for flag in members:
            if flag in fields[1]:
                members[flag].append(value)
        if fields[5] == "61":
            cf_extend.append(value)
        if fields[4] != "=":
            folds.append((value, [int(x, 16) for x in fields[4].split(" ")]))
    parts = [
        "// Generated by crates/keyboard/core/tools/dictation_unicode_tables.py from the iOS 27.0",
        "// simulator's Unicode data (DictationParityTests); don't edit.",
        "",
    ]
    for name, flag, doc in SETS:
        parts.append(table(name, doc, members[flag]))
        parts.append("")
    parts.append(table("CF_EXTEND", "CoreFoundation's Grapheme_Extend set, the marks `folding` drops after a base.", cf_extend))
    parts.append("")
    parts.append("/// `folding([.caseInsensitive, .diacriticInsensitive], locale: nil)` of each scalar it changes.")
    parts.append("#[rustfmt::skip]")
    parts.append("pub(super) static FOLD: &[(u32, &str)] = &[")
    row = []
    for value, out in folds:
        text = "".join("\\u{%X}" % c for c in out)
        row.append('(0x%X, "%s"),' % (value, text))
        if len(row) == 5:
            parts.append("    " + " ".join(row))
            row = []
    if row:
        parts.append("    " + " ".join(row))
    parts.append("];")
    with open(OUT, "w", encoding="utf-8") as out:
        out.write("\n".join(parts) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
